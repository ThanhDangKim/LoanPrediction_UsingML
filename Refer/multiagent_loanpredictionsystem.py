def hyperparam_search(X_res, y_res):
  # small search for RF max_depth
  params = {'n_estimators':[100,200], 'max_depth':[None,10,20]}
  best = None
  best_score = -1
  for n in params['n_estimators']:
    for d in params['max_depth']:
      clf = RandomForestClassifier(n_estimators=n, max_depth=d, class_weight='balanced', random_state=42)
      skf = StratifiedKFold(n_splits=3)
      scores = []
      for train_idx, val_idx in skf.split(X_res, y_res):
        clf.fit(X_res[train_idx], y_res[train_idx])
        probs = clf.predict_proba(X_res[val_idx])[:,1]
        scores.append(roc_auc_score(y_res[val_idx], probs))
      mean_score = np.mean(scores)
      if mean_score>best_score:
        best_score = mean_score
        best = {'n_estimators':n, 'max_depth':d, 'score':float(mean_score)}
  save_json(best, os.path.join(PROJECT_ROOT,'models','best_params.json'))
  print('Hyperparam search done', best)

  return best

