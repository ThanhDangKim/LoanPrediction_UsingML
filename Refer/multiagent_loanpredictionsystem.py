  for i,p in enumerate(probs):
    dec = 'APPROVE' if p<thresh else ('MANUAL_REVIEW' if p<thresh+0.15 else 'REJECT')
    decisions.append({'index': i, 'score': float(p), 'decision': dec})
  save_json({'decisions':decisions}, os.path.join(PROJECT_ROOT,'artifacts','decision_report.json'))
  print('Decision policy applied')
  return decisions

