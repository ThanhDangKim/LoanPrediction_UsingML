def explainability(clf, preprocessor_fitted, X_sample):
  try:
    explainer = shap.TreeExplainer(clf)
    shap_vals = explainer.shap_values(X_sample)
    # for binary
    shap_pos = shap_vals[1]
    mean_abs = np.abs(shap_pos).mean(axis=0)

    # try to get feature names from preprocessor
    try:
      num_cols = preprocessor_fitted.transformers_[0][2]
      ohe = preprocessor_fitted.transformers_[1][1].named_steps['ohe']
      cat_cols = preprocessor_fitted.transformers_[1][2]
      cat_names = list(ohe.get_feature_names_out(cat_cols))
      feat_names = list(num_cols) + cat_names
    except Exception:
      feat_names = [f'f{i}' for i in range(mean_abs.shape[0])]
    idxs = np.argsort(-mean_abs)[:20]
    top_features = [{'feature':feat_names[i],'importance':float(mean_abs[i])} for i in idxs]
    save_json({'top_features':top_features}, os.path.join(PROJECT_ROOT,'artifacts','shap_summary.json'))

    # save summary plot
    try:
      shap.summary_plot(shap_pos, X_sample, feature_names=feat_names, show=False)
      plt.savefig(os.path.join(PROJECT_ROOT,'artifacts','shap_summary.png'), bbox_inches='tight')
      plt.close()
    except Exception:
      pass
    print('SHAP computed')
    return top_features

  except Exception as e:
    print('SHAP failed', e)
    return []

