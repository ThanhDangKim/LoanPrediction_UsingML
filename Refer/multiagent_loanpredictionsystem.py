def population_stability_index(expected, actual, buckets=10):
  # simple PSI for numeric arrays
  expected_perc, bins = np.histogram(expected, bins=buckets)
  actual_perc, _ = np.histogram(actual, bins=bins)
  expected_perc = expected_perc / expected_perc.sum()
  actual_perc = actual_perc / actual_perc.sum()
  psi = np.sum((expected_perc - actual_perc) * np.log((expected_perc + 1e-8)/(actual_perc + 1e-8)))
  return psi

def monitor_model_baseline(feature_name, baseline_vals, recent_vals, threshold=0.1):
  psi = population_stability_index(np.array(baseline_vals), np.array(recent_vals))
  report = {'feature':feature_name, 'psi': float(psi), 'drift': psi>threshold}
  save_json(report, os.path.join(PROJECT_ROOT,'artifacts','monitor_report.json'))
  if psi>threshold:
    save_json({'drift_flag': True, 'reason': f'psi_{feature_name} > {threshold}'}, os.path.join(PROJECT_ROOT,'artifacts','drift_flag.json'))
  print('Monitoring done', report)
  return report

