def decision_policy_apply(clf, preprocessor_fitted, X_sample_df, config=None):
  # config can contain threshold, rules
  thresh = 0.5 if not config else config.get('threshold',0.5)
  X_t = preprocessor_fitted.transform(X_sample_df)
