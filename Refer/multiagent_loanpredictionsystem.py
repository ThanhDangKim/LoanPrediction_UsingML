def train_and_evaluate(X_res, y_res, preprocessor_fitted, X_val, y_val, best_params=None):
  clf = RandomForestClassifier(n_estimators=best_params.get('n_estimators',200), max_depth=best_params.get('max_depth',None), class_weight='balanced', random_state=42)
  clf.fit(X_res, y_res)
  joblib.dump(clf, os.path.join(PROJECT_ROOT,'models','model.joblib'))
  # eval on val
  X_val_t = preprocessor_fitted.transform(X_val)
  probs = clf.predict_proba(X_val_t)[:,1]
  preds = (probs>=0.5).astype(int)
  roc = roc_auc_score(y_val, probs)
  pr = average_precision_score(y_val, probs)
  cr = classification_report(y_val, preds, output_dict=True)
  cm = confusion_matrix(y_val, preds)
  metrics = {'roc_auc':float(roc), 'pr_auc':float(pr), 'classification_report':cr, 'confusion_matrix':cm.tolist()}
  save_json(metrics, os.path.join(PROJECT_ROOT,'models','metrics.json'))
  # save cm image
  fig,ax = plt.subplots(figsize=(4,3))
  sns.heatmap(cm,annot=True,fmt='d',ax=ax)
  fig.savefig(os.path.join(PROJECT_ROOT,'artifacts','confusion_matrix.png'))
  plt.close(fig)
  print('Training done; metrics saved')
  return clf, metrics

